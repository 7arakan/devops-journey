#!/bin/bash

# Сохраняем аргументы в понятные переменные
SERVICE_NAME=$1
ENVIRONMENT=$2

# Записываем текущую дату и время в переменную через подстановку $(...)
NOW=$(date "+%Y-%m-%d %H:%M:%S")

echo "[$NOW] Запуск деплоя сервиса: $SERVICE_NAME"
echo "Целевое окружение: $ENVIRONMENT"

# Проверим, что пользователь передал хотя бы 2 аргумента
echo "Всего передано параметров: $#"

# Имитируем проверку статуса Nginx
systemctl is-active --quiet nginx

# Проверяем код возврата предыдущей команды ($?)
if [ $? -eq 0 ]; then
    echo "✅ Веб-сервер работает, деплой разрешен!"
    exit 0
else
    echo "❌ Ошибка: Веб-сервер остановлен! Деплой отменен."
    exit 1
fi
